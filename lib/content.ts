export function randomHashtags(): string {
  const tags = HASHTAG_SETS[Math.floor(Math.random() * HASHTAG_SETS.length)];
  const extraCount = 1 + Math.floor(Math.random() * 2);
  const shuffled = [...EXTRA_TAGS].sort(() => Math.random() - 0.5);
  return [...tags, ...shuffled.slice(0, extraCount)].join(" ");
}

export function randomChoice<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}
